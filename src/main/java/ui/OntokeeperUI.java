    public void exportScoresForOntology(EqualMetricScoreCard score_card){
        
        
        
        try {
            if(!txtOutputFile.getText().isBlank()){
                
                String output = txtOutputFile.getText() + ".txt";
                
                if(ckJson.isSelected()){
                    
                    
                    FileUtils.writeStringToFile(new File(txtOutputFile.getText().concat(".json")), score_card.toJson().toString(), Charset.forName("UTF-8"));
                }
                else{
                    FileUtils.writeStringToFile(new File(output), score_card.toString(), Charset.forName("UTF-8"));
                }
                
                
            }
            
            
        } catch (IOException ex) {
            System.getLogger(OntokeeperUI.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
        
    }
    
    public void setUIScorePanel(EqualMetricScoreCard score_card){
        
        
        DecimalFormat df = new DecimalFormat("#.###");
        
        double syntactic =  score_card.getSyntacticScore();
        double semantic = score_card.getSemanticScore();
        double pragmatic = score_card.getPragmaticScore();
        double social = 0.00;
        double overall = score_card.getOverallScore();
        
        syntacticPanel.removeAll();
        semanticPanel.removeAll();
        pragmaticPanel.removeAll();
        socialPanel.removeAll();

        ChartPanel syntactic_dial = ScoreDial.getInstance().generateScoreDial(syntactic, 178, 178);
        
        syntacticPanel.add(syntactic_dial, BorderLayout.CENTER);
        
        ChartPanel semantic_dial = ScoreDial.getInstance().generateScoreDial(semantic, 178, 178);
        
        semanticPanel.add(semantic_dial, BorderLayout.CENTER);
        
        pragmaticPanel.add(ScoreDial.getInstance().generateScoreDial(pragmatic, 178, 178), BorderLayout.CENTER);
        
        socialPanel.add(ScoreDial.getInstance().generateScoreDial(social, 178, 178), BorderLayout.CENTER);
        
        socialPanel.setEnabled(false);
        
        this.lblOverallScore.setText(df.format(overall));
        
        this.lblSyntactic1.setText(df.format(syntactic));
        this.lblSemantic.setText(df.format(semantic));
        this.lblPragmatic.setText(df.format(pragmatic));
        
    }
    
    private void saveBatchFunction(String folder_location){
        XSSFWorkbook workbook = new XSSFWorkbook();
        
        Sheet sheet = workbook.createSheet("Results");
        
        
        //create header
        
        Row header = sheet.createRow(0);
        CellStyle header_style = workbook.createCellStyle();
        XSSFFont bold_font = ((XSSFWorkbook) workbook).createFont();
        bold_font.setBold(true);
        header_style.setFont(bold_font);
        
        Cell cell = header.createCell(0);
        cell.setCellValue("ONTOLOGY");
        cell.setCellStyle(header_style);
        
        cell = header.createCell(1);
        cell.setCellValue("SYNTACTIC");
        cell.setCellStyle(header_style);
        
        cell = header.createCell(2);
        cell.setCellValue("Richness");
        cell.setCellStyle(header_style);
        
        
        cell = header.createCell(3);
        cell.setCellValue("Lawfulness");
        cell.setCellStyle(header_style);
        
        cell = header.createCell(4);
        cell.setCellValue("SEMANTIC");
        cell.setCellStyle(header_style);
        
        cell = header.createCell(5);
        cell.setCellValue("Clarity");
        cell.setCellStyle(header_style);
        
        cell = header.createCell(6);
        cell.setCellValue("Consistency");
        cell.setCellStyle(header_style);
        
        cell = header.createCell(7);
        cell.setCellValue("Interpertability");
        cell.setCellStyle(header_style);
        
        cell = header.createCell(8);
        cell.setCellValue("PRAGMATIC");
        cell.setCellStyle(header_style);
        
        cell = header.createCell(9);
        cell.setCellValue("Comprehensiveness");
        cell.setCellStyle(header_style);
        
        cell = header.createCell(10);
        cell.setCellValue("OVERALL SCORE");
        cell.setCellStyle(header_style);
        
        TableModel table_model = batchTable.getModel();
        
        int rowCount = table_model.getRowCount();
        int columnCount = table_model.getColumnCount();
        
        for(int x=0; x < rowCount; x++){
            
            Row createRow = sheet.createRow(x+1);
            
            for(int y=0; y < columnCount; y++){
                
                Object value = table_model.getValueAt(x, y);
                cell = createRow.createCell(y);
                
                if(value instanceof Double){
                    cell.setCellValue((double)value);
                }
                else{
                    cell.setCellValue((String)value);
                }
                
                
            }
            
        }
        
        
        
        
        try {
            
            FileOutputStream outputStream = new FileOutputStream(folder_location);
            workbook.write(outputStream);
            
            
            workbook.close();
            
        } catch (FileNotFoundException ex) {
            System.getLogger(OntokeeperUI.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        } catch (IOException ex) {
            System.getLogger(OntokeeperUI.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
    }
    

    
